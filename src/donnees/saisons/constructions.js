/* Les constructions verbales, en spirale de S1 à S7 (S8 : G8-CONSTR et G8-RECTION).
   Chaque saison reçoit un point de grammaire de plus, rattaché à l'unité
   dont le thème s'y prête. Une étape par semestre :
     S1  verbe + infinitif, jouer à / de, parler à / de
     S2  verbe + à / de + infinitif
     S3  verbe + quelqu'un + à / de (et les pronoms lui, le)
     S4  verbe + préposition et pronoms (y, en, à lui, de lui)
     S5  verbes de parole et de reproche (+ infinitif passé, accuser qn de)
     S6  infinitif ou que + subjonctif ; à ce que
     S7  un verbe, deux constructions (manquer à / de, tenir à / de…)      */

